#!/usr/bin/env node
/**
 * 自动更新 icons.tsx 和 index.ts 文件
 */

const fs = require('fs');
const path = require('path');

const COMPONENTS_DIR = path.join(__dirname, '../src/icon/components');
const ICONS_FILE = path.join(__dirname, '../src/icon/icons.tsx');
const INDEX_FILE = path.join(__dirname, '../src/icon/index.ts');

/**
 * 将文件名转换为图标名称（kebab-case）
 */
function toIconName(filename) {
  return filename
    .replace(/Icon\.tsx$/, '')
    .replace(/([A-Z])/g, '-$1')
    .toLowerCase()
    .replace(/^-/, '');
}

/**
 * 生成 icons.tsx 内容
 */
function generateIconsTsx() {
  const files = fs.readdirSync(COMPONENTS_DIR)
    .filter(f => f.endsWith('.tsx') && f !== 'DismissFilled.tsx');

  const imports = files.map(f => {
    const componentName = f.replace('.tsx', '');
    const importPath = `./components/${componentName}`;
    return `import ${componentName} from '${importPath}';`;
  }).join('\n');

  const iconEntries = files.map(f => {
    const iconName = toIconName(f);
    const componentName = f.replace('.tsx', '');
    return `  '${iconName}': ${componentName},`;
  }).join('\n');

  return `// Auto-generated by scripts/update-icons-index.js
// DO NOT EDIT MANUALLY

${imports}

// 导出图标组件映射，供 Icon 组件使用
export const ICONS = {
${iconEntries}
} as const;
`;
}

/**
 * 生成 index.ts 内容
 */
function generateIndexTs() {
  const files = fs.readdirSync(COMPONENTS_DIR)
    .filter(f => f.endsWith('.tsx') && f !== 'DismissFilled.tsx')
    .sort();

  const exports = files.map(f => {
    const componentName = f.replace('.tsx', '');
    return `export { default as ${componentName} } from './components/${componentName}';`;
  }).join('\n');

  return `// Auto-generated by scripts/update-icons-index.js
// DO NOT EDIT MANUALLY

${exports}
`;
}

/**
 * 主函数
 */
function main() {
  console.log('🔄 Updating icons.tsx...');
  fs.writeFileSync(ICONS_FILE, generateIconsTsx(), 'utf-8');
  console.log('✓  icons.tsx updated');

  console.log('🔄 Updating index.ts...');
  fs.writeFileSync(INDEX_FILE, generateIndexTs(), 'utf-8');
  console.log('✓  index.ts updated');

  const count = fs.readdirSync(COMPONENTS_DIR)
    .filter(f => f.endsWith('.tsx') && f !== 'DismissFilled.tsx').length;

  console.log(`\n✅ Done! Exported ${count} icons.\n`);
}

main();
